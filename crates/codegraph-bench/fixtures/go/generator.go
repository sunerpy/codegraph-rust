package payroll

// Emitter writes CRUD scaffolding for a table.
type Emitter struct {
	Table string
}

// Emit renders the file body, prefixing it with the standard banner.
// The banner literal lives in the BODY as a string constant, so this
// generator source must NOT be classified as generated itself.
func (e *Emitter) Emit() string {
	const banner = "// Code generated by fkit-crud. DO NOT EDIT."
	return banner + "\\n\\npackage " + e.Table + "\\n"
}
